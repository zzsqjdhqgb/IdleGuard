//! Windows notification-area icon implemented directly with Shell_NotifyIcon.
//!
//! The tray runs its own hidden window and Win32 message loop on a dedicated
//! thread. User actions are forwarded to the GPUI thread over a channel; no
//! GPUI state is touched from the Win32 thread.

use std::cell::RefCell;
use std::mem::size_of;
use std::sync::mpsc;
use std::thread::{self, JoinHandle};
use std::time::Duration;

use flume::{Receiver, Sender};
use windows::Win32::Foundation::{ERROR_CLASS_ALREADY_EXISTS, HWND, LPARAM, LRESULT, WPARAM};
use windows::Win32::System::LibraryLoader::GetModuleHandleW;
use windows::Win32::UI::Shell::{
    NIF_ICON, NIF_MESSAGE, NIF_TIP, NIM_ADD, NIM_DELETE, NOTIFYICONDATAW, Shell_NotifyIconW,
};
use windows::Win32::UI::WindowsAndMessaging::{
    AppendMenuW, CreatePopupMenu, CreateWindowExW, DefWindowProcW, DestroyMenu, DestroyWindow,
    DispatchMessageW, GetCursorPos, GetMessageW, MF_SEPARATOR, MF_STRING, MSG, PostMessageW,
    PostQuitMessage, RegisterClassW, RegisterWindowMessageW, SetForegroundWindow, TPM_NONOTIFY,
    TPM_RETURNCMD, TPM_RIGHTBUTTON, TrackPopupMenu, TranslateMessage, WM_APP, WM_CLOSE, WM_COMMAND,
    WM_CONTEXTMENU, WM_DESTROY, WM_LBUTTONUP, WM_NULL, WM_RBUTTONUP, WNDCLASSW, WS_POPUP,
};
use windows::core::{HSTRING, PCWSTR, w};

use crate::platform::icon;
use crate::platform::window;

const TRAY_CALLBACK_MESSAGE: u32 = WM_APP + 1;
const TRAY_ICON_ID: u32 = 1;
const MENU_TOGGLE_ID: u32 = 1;
const MENU_EXIT_ID: u32 = 2;
const TRAY_WINDOW_CLASS: PCWSTR = w!("IdleShutdownTrayWindow");
const TRAY_WINDOW_TITLE: PCWSTR = w!("IdleShutdownTray");

/// Commands generated by the tray and handled on the GPUI main thread.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TrayCommand {
    ToggleMainWindow,
    Exit,
}

struct TrayRuntime {
    sender: Sender<TrayCommand>,
    icon: windows::Win32::UI::WindowsAndMessaging::HICON,
    main_hwnd: isize,
    taskbar_created_message: u32,
}

thread_local! {
    static RUNTIME: RefCell<Option<TrayRuntime>> = const { RefCell::new(None) };
}

/// Owns the tray thread and its command receiver.
pub struct Tray {
    hwnd: isize,
    commands: Receiver<TrayCommand>,
    thread: Option<JoinHandle<()>>,
}

impl Tray {
    pub fn start(main_hwnd: isize) -> Result<Self, String> {
        let (command_tx, command_rx) = flume::unbounded();
        let (ready_tx, ready_rx) = mpsc::channel();
        let thread = thread::Builder::new()
            .name("idle-shutdown-tray".to_string())
            .spawn(move || {
                let result = run_tray_thread(main_hwnd, command_tx, &ready_tx);
                if let Err(error) = result {
                    let _ = ready_tx.send(Err(error.clone()));
                    crate::diag::error("托盘线程退出", &error);
                }
            })
            .map_err(|error| format!("无法创建托盘线程：{error}"))?;

        match ready_rx.recv_timeout(Duration::from_secs(6)) {
            Ok(Ok(hwnd)) => Ok(Self {
                hwnd,
                commands: command_rx,
                thread: Some(thread),
            }),
            Ok(Err(error)) => {
                let _ = thread.join();
                Err(error)
            }
            Err(_) => Err("托盘初始化超时。".to_string()),
        }
    }

    pub fn commands(&self) -> &Receiver<TrayCommand> {
        &self.commands
    }

    /// Remove the icon and stop the tray message loop. Safe to call more than
    /// once via `Drop`.
    pub fn remove(&mut self) {
        if let Some(thread) = self.thread.take() {
            let hwnd = window::hwnd_from_isize(self.hwnd);
            unsafe {
                let _ = PostMessageW(Some(hwnd), WM_CLOSE, WPARAM(0), LPARAM(0));
            }
            let _ = thread.join();
        }
    }
}

impl Drop for Tray {
    fn drop(&mut self) {
        self.remove();
    }
}

fn run_tray_thread(
    main_hwnd: isize,
    sender: Sender<TrayCommand>,
    ready: &mpsc::Sender<Result<isize, String>>,
) -> Result<(), String> {
    let icon = icon::create_app_icon(64).ok_or_else(|| "无法创建托盘图标。".to_string())?;

    let module =
        unsafe { GetModuleHandleW(None) }.map_err(|error| format!("无法获取模块句柄：{error}"))?;
    let instance = windows::Win32::Foundation::HINSTANCE(module.0);

    let window_class = WNDCLASSW {
        lpfnWndProc: Some(tray_window_proc),
        hInstance: instance,
        lpszClassName: TRAY_WINDOW_CLASS,
        ..Default::default()
    };
    let registered = unsafe { RegisterClassW(&window_class) };
    if registered == 0 {
        let error = unsafe { windows::Win32::Foundation::GetLastError() };
        if error != ERROR_CLASS_ALREADY_EXISTS {
            icon::destroy_icon(icon);
            return Err(format!("无法注册托盘窗口类（错误码 {}）。", error.0));
        }
    }

    let hwnd = match unsafe {
        CreateWindowExW(
            Default::default(),
            TRAY_WINDOW_CLASS,
            TRAY_WINDOW_TITLE,
            WS_POPUP,
            0,
            0,
            0,
            0,
            None,
            None,
            Some(instance),
            None,
        )
    } {
        Ok(hwnd) => hwnd,
        Err(error) => {
            icon::destroy_icon(icon);
            return Err(format!("无法创建托盘窗口：{error}"));
        }
    };

    let taskbar_created_message = unsafe { RegisterWindowMessageW(w!("TaskbarCreated")) };

    RUNTIME.with(|slot| {
        *slot.borrow_mut() = Some(TrayRuntime {
            sender,
            icon,
            main_hwnd,
            taskbar_created_message,
        });
    });

    // At login the shell may not be ready to accept notification icons during
    // the first few hundred milliseconds. Retry briefly before giving up so
    // auto-start does not fail spuriously.
    let mut icon_added = false;
    for attempt in 0..10 {
        if add_icon(hwnd) {
            icon_added = true;
            break;
        }
        if attempt < 9 {
            thread::sleep(Duration::from_millis(200));
        }
    }
    if !icon_added {
        cleanup_runtime();
        unsafe {
            let _ = DestroyWindow(hwnd);
        }
        return Err("Shell_NotifyIcon 无法添加托盘图标（已重试）。".to_string());
    }

    ready
        .send(Ok(hwnd.0 as isize))
        .map_err(|_| "主线程已退出。".to_string())?;

    let mut message = MSG::default();
    loop {
        let result = unsafe { GetMessageW(&mut message, None, 0, 0) };
        if result.0 <= 0 {
            break;
        }
        unsafe {
            let _ = TranslateMessage(&message);
            DispatchMessageW(&message);
        }
    }

    // WM_DESTROY normally removes the icon; this covers a message-loop exit
    // without a destroy message.
    cleanup_runtime();
    Ok(())
}

fn notify_icon_data(
    hwnd: HWND,
    icon: windows::Win32::UI::WindowsAndMessaging::HICON,
) -> NOTIFYICONDATAW {
    let mut data = NOTIFYICONDATAW {
        cbSize: size_of::<NOTIFYICONDATAW>() as u32,
        hWnd: hwnd,
        uID: TRAY_ICON_ID,
        uFlags: NIF_MESSAGE | NIF_ICON | NIF_TIP,
        uCallbackMessage: TRAY_CALLBACK_MESSAGE,
        hIcon: icon,
        ..Default::default()
    };
    let tooltip: Vec<u16> = "无操作自动关机 - 左键显示/隐藏，右键菜单"
        .encode_utf16()
        .take(127)
        .collect();
    data.szTip[..tooltip.len()].copy_from_slice(&tooltip);
    data
}

fn add_icon(hwnd: HWND) -> bool {
    RUNTIME.with(|slot| {
        let slot = slot.borrow();
        let Some(runtime) = slot.as_ref() else {
            return false;
        };
        let data = notify_icon_data(hwnd, runtime.icon);
        unsafe { Shell_NotifyIconW(NIM_ADD, &data).as_bool() }
    })
}

fn remove_icon(hwnd: HWND) {
    let data = RUNTIME.with(|slot| {
        let slot = slot.borrow();
        let runtime = slot.as_ref()?;
        Some(notify_icon_data(hwnd, runtime.icon))
    });
    if let Some(data) = data {
        unsafe {
            let _ = Shell_NotifyIconW(NIM_DELETE, &data);
        }
    }
}

fn cleanup_runtime() {
    RUNTIME.with(|slot| {
        if let Some(runtime) = slot.borrow_mut().take() {
            icon::destroy_icon(runtime.icon);
        }
    });
}

fn show_context_menu(hwnd: HWND) {
    let main_hwnd = RUNTIME.with(|slot| slot.borrow().as_ref().map(|runtime| runtime.main_hwnd));
    let Some(main_hwnd) = main_hwnd else {
        return;
    };
    let main_hwnd = window::hwnd_from_isize(main_hwnd);
    let toggle_label = if window::is_main_shown(main_hwnd) {
        HSTRING::from("隐藏主界面")
    } else {
        HSTRING::from("显示主界面")
    };

    let menu = match unsafe { CreatePopupMenu() } {
        Ok(menu) => menu,
        Err(error) => {
            crate::diag::error("创建托盘菜单", &error.to_string());
            return;
        }
    };

    unsafe {
        let _ = AppendMenuW(menu, MF_STRING, MENU_TOGGLE_ID as usize, &toggle_label);
        let _ = AppendMenuW(menu, MF_SEPARATOR, 0, None);
        let _ = AppendMenuW(menu, MF_STRING, MENU_EXIT_ID as usize, w!("退出"));
        let _ = SetForegroundWindow(hwnd);

        let mut point = windows::Win32::Foundation::POINT::default();
        let _ = GetCursorPos(&mut point);
        let command = TrackPopupMenu(
            menu,
            TPM_RETURNCMD | TPM_RIGHTBUTTON | TPM_NONOTIFY,
            point.x,
            point.y,
            None,
            hwnd,
            None,
        )
        .0 as u32;
        let _ = PostMessageW(Some(hwnd), WM_NULL, WPARAM(0), LPARAM(0));
        let _ = DestroyMenu(menu);

        match command {
            MENU_TOGGLE_ID => dispatch(TrayCommand::ToggleMainWindow),
            MENU_EXIT_ID => dispatch(TrayCommand::Exit),
            _ => {}
        }
    }
}

fn dispatch(command: TrayCommand) {
    RUNTIME.with(|slot| {
        if let Some(runtime) = slot.borrow().as_ref() {
            let _ = runtime.sender.send(command);
        }
    });
}

unsafe extern "system" fn tray_window_proc(
    hwnd: HWND,
    message: u32,
    wparam: WPARAM,
    lparam: LPARAM,
) -> LRESULT {
    let taskbar_message = RUNTIME.with(|slot| {
        slot.borrow()
            .as_ref()
            .map(|runtime| runtime.taskbar_created_message)
    });

    if message == TRAY_CALLBACK_MESSAGE {
        match lparam.0 as u32 {
            WM_LBUTTONUP => dispatch(TrayCommand::ToggleMainWindow),
            WM_RBUTTONUP | WM_CONTEXTMENU => show_context_menu(hwnd),
            _ => {}
        }
        return LRESULT(0);
    }

    if message == WM_COMMAND {
        match (wparam.0 & 0xFFFF) as u32 {
            MENU_TOGGLE_ID => dispatch(TrayCommand::ToggleMainWindow),
            MENU_EXIT_ID => dispatch(TrayCommand::Exit),
            _ => {}
        }
        return LRESULT(0);
    }

    match message {
        WM_CLOSE => {
            unsafe {
                let _ = DestroyWindow(hwnd);
            }
            LRESULT(0)
        }
        WM_DESTROY => {
            remove_icon(hwnd);
            cleanup_runtime();
            unsafe { PostQuitMessage(0) };
            LRESULT(0)
        }
        _ if taskbar_message.is_some_and(|taskbar| taskbar != 0 && message == taskbar) => {
            // Explorer restarted and discarded existing notification icons.
            let _ = add_icon(hwnd);
            LRESULT(0)
        }
        _ => unsafe { DefWindowProcW(hwnd, message, wparam, lparam) },
    }
}
